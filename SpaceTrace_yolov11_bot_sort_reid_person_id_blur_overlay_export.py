def _parse_filename_timestamp(video_path):
    """
    Look for a CCTV-style 14-digit timestamp in the filename:
    YYYYMMDDHHMMSS, for example 20260214083552.

    Returns the FULL datetime from filename, not only the time.
    """
    stem = Path(video_path).stem
    candidates = re.findall(r"(20\d{12})", stem)
    for ts in candidates:
        try:
            return datetime.strptime(ts, "%Y%m%d%H%M%S"), f"filename timestamp {ts}"
        except Exception:
            pass
    return None, "no filename timestamp"

def infer_recording_start(video_path, manual_date, manual_start_time):
    """
    Recording start logic:
    1. If START_TIME_MANUAL is provided, use DATE + START_TIME_MANUAL.
    2. If START_TIME_MANUAL is empty, use the FULL datetime from filename as backup.
    3. If filename has no timestamp, use DATE + 00:00:00.

    This function never uses OCR, video metadata, file creation time, or notebook runtime.
    """
    manual_date = str(manual_date).strip()
    manual_start_time = str(manual_start_time).strip()

    if manual_start_time:
        return datetime.strptime(f"{manual_date} {manual_start_time}", "%Y-%m-%d %H:%M:%S"), "manual DATE + START_TIME_MANUAL"

    if USE_FILENAME_DATETIME_BACKUP:
        file_dt, source = _parse_filename_timestamp(video_path)
        if file_dt is not None:
            return file_dt, source + " full datetime backup"

    return datetime.strptime(f"{manual_date} 00:00:00", "%Y-%m-%d %H:%M:%S"), "manual DATE + default 00:00:00"

