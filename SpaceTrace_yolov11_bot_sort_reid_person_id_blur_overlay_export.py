def _clip_box(x1, y1, x2, y2, width, height):
    """Clip box coordinates to the image boundary and return integers."""
    x1 = max(0, min(width - 1, int(round(x1))))
    y1 = max(0, min(height - 1, int(round(y1))))
    x2 = max(0, min(width, int(round(x2))))
    y2 = max(0, min(height, int(round(y2))))
    if x2 <= x1 or y2 <= y1:
        return None
    return x1, y1, x2, y2


def _blur_roi(frame, x1, y1, x2, y2, blur_strength=51):
    """Blur only the inside of the bounding box."""
    roi = frame[y1:y2, x1:x2]
    if roi.size == 0:
        return frame

    # Gaussian kernel must be odd and positive.
    k = max(15, int(blur_strength))
    if k % 2 == 0:
        k += 1

    blurred = cv2.GaussianBlur(roi, (k, k), 0)
    frame[y1:y2, x1:x2] = blurred
    return frame


def _draw_person_id_label(frame, label, x1, y1, x2, y2):
    """Draw final person_id label and bounding box. No raw track_id is shown."""
    label = str(label)

    # Bounding box outline
    cv2.rectangle(frame, (x1, y1), (x2, y2), (255, 255, 255), 2)

    font = cv2.FONT_HERSHEY_SIMPLEX
    font_scale = 0.7
    thickness = 2
    (tw, th), baseline = cv2.getTextSize(label, font, font_scale, thickness)

    # Place label above the box if possible, otherwise inside the top of the box.
    pad = 5
    label_x1 = x1
    label_y1 = max(0, y1 - th - baseline - 2 * pad)
    label_x2 = min(frame.shape[1], x1 + tw + 2 * pad)
    label_y2 = min(frame.shape[0], label_y1 + th + baseline + 2 * pad)

    # If the label would be outside the image, move it inside the box.
    if y1 - th - baseline - 2 * pad < 0:
        label_y1 = y1
        label_y2 = min(frame.shape[0], y1 + th + baseline + 2 * pad)

    cv2.rectangle(frame, (label_x1, label_y1), (label_x2, label_y2), (0, 0, 0), -1)
    cv2.putText(
        frame,
        label,
        (label_x1 + pad, label_y2 - baseline - pad),
        font,
        font_scale,
        (255, 255, 255),
        thickness,
        cv2.LINE_AA,
    )
    return frame


